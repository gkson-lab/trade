#!/usr/bin/env python3
"""Build js/symbols.js from the listing snapshots in data/source/.

Sources (snapshots, committed so the build is reproducible offline):
  data/source/{nasdaq,nyse,amex}.json  - github.com/rreichel3/US-Stock-Symbols
  data/source/sp500.csv                - github.com/datasets/s-and-p-500-companies

Prices, market caps and volumes are only used as *starting points* for the
simulation. Everything after t=0 is synthetic.
"""
import csv, json, math, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "source")

SECTORS = ["Technology", "Health Care", "Finance", "Consumer Discretionary",
           "Consumer Staples", "Industrials", "Energy", "Utilities",
           "Real Estate", "Basic Materials", "Telecommunications", "Miscellaneous"]

NAME_JUNK = re.compile(
    r"\b(Common Stock|Ordinary Shares?|American Depositary Shares?|American Depository Shares?|"
    r"Class [A-C]|Common Shares?|Depositary Shares?|Subordinate Voting Shares|"
    r"New|Inc\.?|Incorporated|Corporation|Corp\.?|Holdings?|Ltd\.?|Limited|plc|N\.V\.|S\.A\.|L\.P\.)\b",
    re.I)

def clean_name(n):
    n = n.split(" each representing")[0].split(" representing")[0].split(" (")[0]
    n = NAME_JUNK.sub("", n)
    n = re.sub(r"[ ,]+$", "", re.sub(r"\s{2,}", " ", n)).strip(" ,.-")
    return n[:40] or "Unnamed"

def num(s):
    try:
        return float(str(s).replace("$", "").replace(",", ""))
    except ValueError:
        return 0.0

def main():
    sp = set()
    with open(os.path.join(SRC, "sp500.csv"), newline="") as f:
        for r in csv.DictReader(f):
            sp.add(r["Symbol"].replace(".", "/"))
    out, seen = [], set()
    for ex_i, ex in enumerate(["nasdaq", "nyse", "amex"]):
        for r in json.load(open(os.path.join(SRC, ex + ".json"))):
            sym = r["symbol"].strip()
            if not sym or "^" in sym or sym in seen:
                continue
            # drop warrants/units/rights (W, U, R suffix on 5-letter Nasdaq symbols)
            if ex == "nasdaq" and len(sym) == 5 and sym[-1] in "WUR":
                continue
            if "/" in sym and sym not in sp:
                continue
            price = num(r["lastsale"])
            if price < 0.2:
                continue
            vol = max(num(r["volume"]), 1000.0)
            mcap = num(r["marketCap"])
            if mcap <= 0:
                mcap = price * vol * 40  # crude float-turnover estimate
            sector = r["sector"] if r["sector"] in SECTORS else "Miscellaneous"
            seen.add(sym)
            out.append([sym.replace("/", "."), clean_name(r["name"]), ex_i,
                        SECTORS.index(sector), round(price, 4 if price < 1 else 2),
                        round(mcap / 1e6, 2), int(vol), 1 if sym in sp else 0])
    out.sort(key=lambda x: -x[5])
    js = ("/* Generated by tools/build_symbols.py - do not edit by hand. */\n"
          "window.T = window.T || {};\n"
          "T.SECTORS = " + json.dumps(SECTORS) + ";\n"
          "T.EXCHANGES = [\"NASDAQ\",\"NYSE\",\"AMEX\"];\n"
          "/* [symbol, name, exchange, sector, startPrice, marketCap($M), avgVolume, sp500] */\n"
          "T.SYMBOLS = " + json.dumps(out, separators=(",", ":")) + ";\n")
    with open(os.path.join(ROOT, "js", "symbols.js"), "w") as f:
        f.write(js)
    print(len(out), "symbols,", sum(x[7] for x in out), "S&P 500 members,", len(js) // 1024, "KB")

if __name__ == "__main__":
    main()
